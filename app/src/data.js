const L = (k, d) => JSON.parse(localStorage.getItem("blinq.d." + k) || d);
const S = (k, v) => localStorage.setItem("blinq.d." + k, JSON.stringify(v));
export const contacts = () => L("c", "{}");
export const saveContact = (id, c) => { const a = contacts(); a[id] = { ...a[id], ...c }; S("c", a); };
export const chat = (id) => L("m." + id, "[]");
export const saveChat = (id, m) => S("m." + id, m);
export const addMsg = (id, msg) => { const m = chat(id); m.push(msg); saveChat(id, m); };
export const patchMsg = (id, i, fn) => { const m = chat(id), x = m.find((y) => y.i === i); if (x) { fn(x); saveChat(id, m); } };
export const myName = () => localStorage.getItem("blinq.name") || "";
export const setMyName = (n) => localStorage.setItem("blinq.name", n);
export const pref = (k, d) => localStorage.getItem("blinq.p." + k) ?? d;
export const setPref = (k, v) => localStorage.setItem("blinq.p." + k, String(v));
